#!/usr/bin/env python3
"""Build local downloads from an explicit source allowlist. Installs nothing."""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
import hashlib
import json

ROOT = Path(__file__).resolve().parent
DIST = ROOT / 'dist'
RUNTIME = ('manifest.json', 'cleanup.js', 'background.js', 'popup.html', 'popup.css', 'popup.js', 'icon.svg')


def archive(path, entries):
    with ZipFile(path, 'w', ZIP_DEFLATED) as output:
        for source, target in sorted(entries, key=lambda item: str(item[1])):
            output.write(source, str(target))


def main():
    DIST.mkdir(exist_ok=True)
    standalone = ROOT / 'standalone/userChrome.css'
    standalone.parent.mkdir(exist_ok=True)
    parts = [ROOT / 'chrome/zenfx' / name for name in ('theme.css', 'compact.css', 'features.css', 'custom.css')]
    standalone.write_text('/* ZenFX standalone — Firefox 158 / macOS. See README.md.\n'
                          ' * Generated by build.py. Install this file OR the modular chrome folder. */\n\n'
                          + '\n\n'.join(p.read_text() for p in parts))
    addon_version = json.loads((ROOT / 'companion/manifest.json').read_text())['version']
    addon = DIST / f'ZenFX-Tab-Cleanup-{addon_version}-unsigned.zip'
    for old in DIST.glob('ZenFX-Tab-Cleanup-*-unsigned.zip'):
        if old != addon: old.unlink()
    archive(addon, [(ROOT / 'companion' / name, name) for name in RUNTIME])
    archive(DIST / 'ZenFX-Appearance.zip', [(standalone, 'chrome/userChrome.css'), (ROOT / 'appearance/README.md', 'README.md')])
    # Never recurse into the repository root: profiles, .git, and dist cannot enter setup.
    sources = [ROOT / name for name in ('README.md', 'START-HERE.md', 'Install.command', 'Install.cmd', 'Install.sh', 'build.py', '.gitignore')]
    for folder in ('chrome', 'standalone', 'optional-chrome', 'companion', 'installer', 'appearance', 'docs'):
        sources += [p for p in (ROOT / folder).rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.suffix not in ('.pyc', '.pyo') and p.name != '.DS_Store']
    hashes = ROOT / 'SHA256.json'
    hashes.write_text(json.dumps({str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(sources)}, indent=2) + '\n')
    archive(DIST / 'ZenFX-Setup.zip', [(p, Path('ZenFX') / p.relative_to(ROOT)) for p in sources + [hashes]] + [(addon, 'ZenFX/packages/' + addon.name)])
    (DIST / 'SHA256SUMS.txt').write_text(''.join(hashlib.sha256(p.read_bytes()).hexdigest() + '  ' + p.name + '\n' for p in sorted(DIST.glob('*.zip'))))
    print('Built appearance, full setup, and unsigned cleanup downloads in dist/.')


if __name__ == '__main__':
    main()
